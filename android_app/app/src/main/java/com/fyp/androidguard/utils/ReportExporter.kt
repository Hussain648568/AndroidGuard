package com.fyp.androidguard.utils

import android.content.Context
import android.content.Intent
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.widget.Toast
import androidx.core.content.FileProvider
import com.fyp.androidguard.models.AnalysisReport
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object ReportExporter {

    fun shareReportText(context: Context, appName: String, report: AnalysisReport) {
        val dateStr = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.getDefault()).format(Date())
        val engine = report.engine ?: "Static Analysis"

        val sb = StringBuilder()
        sb.appendLine("🛡️ ANDROIDGUARD ANALYSIS REPORT")
        sb.appendLine("=========================================")
        sb.appendLine("Application: $appName")
        sb.appendLine("Analysis Date: $dateStr")
        sb.appendLine("Analysis Engine: $engine")
        sb.appendLine("SHA-256 Fingerprint: ${report.sha256 ?: "N/A"}")
        sb.appendLine("Definitive Leaks Detected: ${report.definitive_leaks_count}")
        sb.appendLine()
        sb.appendLine("🚨 KEY LEAK FINDINGS (${report.findings.size} Total):")
        sb.appendLine("-----------------------------------------")

        report.findings.take(15).forEachIndexed { index, leak ->
            sb.appendLine("[$index] Confidence: ${leak.confidence ?: "CONFIRMED"}")
            sb.appendLine("  SOURCE: ${leak.source?.target_signature ?: leak.source?.method ?: "N/A"}")
            sb.appendLine("  SINK:   ${leak.sink?.target_signature ?: leak.sink?.method ?: "N/A"}")
            val loc = leak.source?.className ?: leak.sink?.className ?: ""
            if (loc.isNotEmpty()) sb.appendLine("  Class:  $loc")
            sb.appendLine()
        }

        if (report.findings.size > 15) {
            sb.appendLine("... and ${report.findings.size - 15} more leak paths documented in full report.")
        }
        sb.appendLine("Generated by AndroidGuard Privacy & Vulnerability Scanner")

        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, "Security Audit: $appName")
            putExtra(Intent.EXTRA_TEXT, sb.toString())
        }
        val chooser = Intent.createChooser(intent, "Share Security Audit Report via")
        context.startActivity(chooser)
    }

    fun exportAndSharePdf(context: Context, appName: String, report: AnalysisReport) {
        val pdfDocument = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create() // Standard A4 (595 x 842 pt)
        val page = pdfDocument.startPage(pageInfo)
        val canvas = page.canvas

        val titlePaint = Paint().apply {
            color = Color.rgb(13, 27, 42)
            textSize = 20f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            isAntiAlias = true
        }

        val subtitlePaint = Paint().apply {
            color = Color.rgb(65, 90, 119)
            textSize = 11f
            typeface = Typeface.DEFAULT
            isAntiAlias = true
        }

        val headerPaint = Paint().apply {
            color = Color.rgb(27, 38, 59)
            textSize = 13f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            isAntiAlias = true
        }

        val textPaint = Paint().apply {
            color = Color.rgb(33, 33, 33)
            textSize = 10f
            typeface = Typeface.DEFAULT
            isAntiAlias = true
        }

        val boldPaint = Paint().apply {
            color = Color.rgb(33, 33, 33)
            textSize = 10f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            isAntiAlias = true
        }

        val dateStr = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.getDefault()).format(Date())

        var y = 45f

        // Document Header
        canvas.drawText("🛡️ ANDROIDGUARD ANALYSIS REPORT", 36f, y, titlePaint)
        y += 18f
        canvas.drawText("Automated Multi-Tier Static Analysis | Generated on: $dateStr", 36f, y, subtitlePaint)
        y += 24f

        // Divider
        val linePaint = Paint().apply {
            color = Color.rgb(224, 224, 224)
            strokeWidth = 1.5f
        }
        canvas.drawLine(36f, y, 559f, y, linePaint)
        y += 22f

        // Summary Box
        val boxPaint = Paint().apply {
            color = if (report.definitive_leaks_count > 0) Color.rgb(255, 235, 238) else Color.rgb(232, 245, 233)
            style = Paint.Style.FILL
        }
        canvas.drawRoundRect(36f, y, 559f, y + 85f, 8f, 8f, boxPaint)

        canvas.drawText("TARGET APPLICATION: $appName", 50f, y + 24f, headerPaint)
        canvas.drawText("Analysis Engine: ${report.engine ?: "Static Analysis"}", 50f, y + 42f, textPaint)
        canvas.drawText("SHA-256: ${report.sha256?.take(36) ?: "N/A"}...", 50f, y + 58f, textPaint)

        val leakStatusColor = if (report.definitive_leaks_count > 0) Color.rgb(211, 47, 47) else Color.rgb(46, 125, 50)
        val leakStatusPaint = Paint().apply {
            color = leakStatusColor
            textSize = 14f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        canvas.drawText(
            if (report.definitive_leaks_count > 0) "Definitive Leaks Found: ${report.definitive_leaks_count}" else "Clean - No Leaks Detected",
            50f, y + 76f, leakStatusPaint
        )
        y += 105f

        // Detailed Findings Header
        canvas.drawText("DOCUMENTED VULNERABILITY FLOWS (Sample Excerpts):", 36f, y, headerPaint)
        y += 18f

        report.findings.take(9).forEachIndexed { index, leak ->
            canvas.drawText("#$index [${leak.confidence ?: "CONFIRMED"}] Flow Path", 40f, y, boldPaint)
            y += 14f
            val srcText = "SOURCE: " + (leak.source?.target_signature ?: leak.source?.method ?: "N/A").take(85)
            canvas.drawText(srcText, 50f, y, textPaint)
            y += 13f
            val snkText = "SINK:   " + (leak.sink?.target_signature ?: leak.sink?.method ?: "N/A").take(85)
            canvas.drawText(snkText, 50f, y, textPaint)
            y += 18f
        }

        // Footer
        canvas.drawLine(36f, 790f, 559f, 790f, linePaint)
        canvas.drawText("AndroidGuard Automated FYP Security System — Confidential Audit", 36f, 805f, subtitlePaint)

        pdfDocument.finishPage(page)

        // Save PDF to cache dir
        val safeName = appName.replace(" ", "_")
        val pdfFile = File(context.cacheDir, "AndroidGuard_${safeName}_Report.pdf")

        try {
            FileOutputStream(pdfFile).use { out ->
                pdfDocument.writeTo(out)
            }
            pdfDocument.close()

            // Share PDF via FileProvider
            val uri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                pdfFile
            )

            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "application/pdf"
                putExtra(Intent.EXTRA_STREAM, uri)
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }
            val chooser = Intent.createChooser(shareIntent, "Save or Share Audit PDF via")
            context.startActivity(chooser)

        } catch (e: Exception) {
            pdfDocument.close()
            Toast.makeText(context, "Failed to export PDF: ${e.message}", Toast.LENGTH_SHORT).show()
        }
    }
}
